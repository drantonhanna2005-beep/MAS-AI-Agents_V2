/* حالة اللغة: مصدر واحد للحقيقة عبر window.MAS + getter حي — لا تتأثر بأي stale closure */
window.MAS = window.MAS || {};
window.MAS.lang = localStorage.getItem("mas-lang") || "ar";
Object.defineProperty(window, "LANG", { get: () => window.MAS.lang, configurable: true });

function t(key, vars) {
  const L = window.MAS.lang;
  let s = (I18N[L] && I18N[L][key] != null) ? I18N[L][key] : (I18N.ar[key] != null ? I18N.ar[key] : key);
  if (vars) for (const k in vars) s = s.replaceAll("{" + k + "}", vars[k]);
  return s;
}

function applyI18n() {
  const L = window.MAS.lang;
  document.documentElement.lang = L;
  document.documentElement.dir = L === "ar" ? "rtl" : "ltr";
  document.title = t("app_title");
  const d = I18N[L] || I18N.ar;
  $$("[data-i18n]").forEach((el) => { const v = d[el.dataset.i18n]; if (v != null) el.innerHTML = v; });
  $$("[data-i18n-ph]").forEach((el) => { const v = d[el.dataset.i18nPh]; if (v != null) el.placeholder = v; });
  $$("[data-i18n-title]").forEach((el) => { const v = d[el.dataset.i18nTitle]; if (v != null) el.title = v; });
  const btn = $("#langBtn");
  if (btn) btn.textContent = L === "ar" ? "🌐 EN" : "🌐 عربي";
}

async function setLang(l) {
  if (l === window.MAS.lang) return;
  window.MAS.lang = l;
  localStorage.setItem("mas-lang", l);
  applyI18n();
  document.dispatchEvent(new CustomEvent("langchange"));
}

/* زر اللغة مُوصّل هنا — عند صاحب الحالة نفسه، فلا مجال لأي تناقض */
document.getElementById("langBtn")?.addEventListener("click", () =>
  setLang(window.MAS.lang === "ar" ? "en" : "ar"));
